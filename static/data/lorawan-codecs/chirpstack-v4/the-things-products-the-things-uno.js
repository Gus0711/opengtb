var LED_STATES = ['off', 'on']

function decodeUplink(input) {
  var data = {};
  data.ledState = LED_STATES[input.bytes[0]];
  return {
    data: data,
  };
}

function encodeDownlink(input) {
  var i = LED_STATES.indexOf(input.data.ledState);
  if (i === -1) {
    return {
      errors: ['unknown led state'],
    };
  }
  return {
    bytes: [i],
    fPort: 1,
  };
}

